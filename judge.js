// 審査員への頼み文。誰の答えかは伏せる。お世辞を構造で封じる
function judgePrompt(items){
  const body = items.map(it => `${it.label}　場面：${it.setup}\n　返し：「${it.r}」`).join("\n\n");
  return `あなたは辛口のお笑い審査員です。次の${items.length}本は、それぞれ「場面」と、その場で出た「返し」の組です。誰の返しかは伏せてあります。

それぞれについて「10人の飲み会でこの返しが出たら、何人が吹き出すか（0〜10）」を予測してください。

ルール：
・${items.length}本のうち、少なくとも3本は2人以下にする。全部を持ち上げない。
・「面白い」「いい」「素晴らしい」「秀逸」は使わない。各本は1行だけ：どこで笑いかけて、どこで冷めるか。
・文字だけで判断する。言い方や表情は考えない。
・最後に、上から順に全部の記号を並べる。

出力はこの形だけにしてください（前置き・まとめは不要）：
A: n人｜一行
B: n人｜一行
…
順位: A>B>…

${body}`;
}

// 審査員の答えを読む。人数と順位を拾う。順位が無ければ人数から作る
function parseJudge(text, labels){
  const n = {};
  for (const m of text.matchAll(/([A-H])\s*[:：]\s*(\d{1,2})\s*人/g)) n[m[1]] = Math.min(10, +m[2]);
  let order = [];
  const m = text.match(/順位\s*[:：]\s*([A-H][A-H\s>＞,、]*)/);
  if (m) order = [...m[1].matchAll(/[A-H]/g)].map(x=>x[0]).filter((x,i,a)=>a.indexOf(x)===i);
  if (order.length !== labels.length) order = labels.slice().sort((a,b)=>(n[b]??-1)-(n[a]??-1));
  const ok = labels.every(l => n[l] !== undefined);
  return { n, order, ok };
}

